const sha = (value) => crypto.createHash('sha256').update(value).digest('hex');
const decisions = [];
const files = new Map();

for (const [key, allocation] of reviewed) {
  const item = byKey.get(key);
  if (!item) throw new Error(`${key}: not present in the 203-group cohort`);
  if (!item.hornerEnglish.includes(allocation)) throw new Error(`${key}: allocation is not verbatim Horner text: ${allocation}`);
  const [book, chapter, verseAndRow] = key.split('.');
  const [verse, rowIndexText] = verseAndRow.split(':');
  const gospel = book === 'Matt' ? 'matthew' : book.toLowerCase();
  const rowIndex = Number(rowIndexText);
  const exactPeerEvidence = Object.fromEntries(Object.entries(item.peerEvidence).filter(([, glosses]) => glosses.length));
  const decision = {
    key, sourceReference: item.sourceReference, gospel, chapter, verse, rowIndex,
    sourceToken: item.sourceToken, coptic: item.coptic, allocation,
    hornerEnglish: item.hornerEnglish, scriptoriumEnglish: item.scriptoriumEnglish,
    comparativeEvidence: exactPeerEvidence,
    method: 'HORNER_WORDING_COMPARATIVE_ORDER_ALIGNMENT',
    reviewBasis: 'Horner supplies the displayed wording; Scriptorium and independent tradition order establish the semantic neighborhood; Coptic source identity or morphology identifies the group.',
    status: 'internally-adjudicated-not-independent-scholarly-review',
  };
  decision.decisionSha256 = sha(JSON.stringify(decision));
  decisions.push(decision);
}

if (APPLY) {
  for (const decision of decisions) {
    const file = path.join(ROOT, 'data', decision.gospel, decision.chapter, `${decision.verse}.json`);
    const data = files.get(file) ?? JSON.parse(fs.readFileSync(file, 'utf8'));
    files.set(file, data);
    const cell = data.rows[decision.rowIndex]?.coptic;
    if (cell?.provenance?.sourceToken !== decision.sourceToken) throw new Error(`${decision.key}: source-token identity changed`);
    if (cell.gloss?.gloss === decision.allocation && cell.provenance?.hornerComparativeAdjudication203?.decisionSha256 === decision.decisionSha256) continue;
    if (cell.gloss?.gloss) throw new Error(`${decision.key}: comparative adjudication would overwrite English`);
    cell.gloss = {
      gloss: decision.allocation,
      source: 'Horner',
      tooltip: 'George W. Horner · Sahidic wording aligned by comparative order; corroborated by Scriptorium',
    };
    cell.provenance.hornerComparativeAdjudication203 = {
      decisionSha256: decision.decisionSha256,
      method: decision.method,
      status: decision.status,
    };
  }
  for (const [file, data] of files) fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}

const report = { generatedAt: new Date().toISOString(), applied: APPLY, sourceCohort: 203, admittedGroups: decisions.length, remainingGroups: 203 - decisions.length, decisions };
fs.writeFileSync(path.join(ROOT, 'docs/audits/coptic-203-comparative-reviewed-adjudication.json'), `${JSON.stringify(report, null, 2)}\n`);
